def get_selected_language(preferences=None):
    prefs = preferences
    if prefs is None:
        try:
            addons = bpy.context.preferences.addons
            for addon_id in ("ManWTool", ((__package__ or "").split(".")[0] if __package__ else "")):
                if addon_id and addon_id in addons:
                    prefs = addons[addon_id].preferences
                    break
        except Exception:
            prefs = None
    return (getattr(prefs, "ui_language", "AUTO") or "AUTO").upper()


def get_effective_language(preferences=None):
    selected = get_selected_language(preferences=preferences)
    if selected in {"ES", "EN", "FR", "DE", "IT", "PT"}:
        return selected.lower()

    try:
        blender_language = (bpy.context.preferences.view.language or "").lower()
    except Exception:
        blender_language = ""

    blender_map = {
        "es": "es",
        "en": "en",
        "fr": "fr",
        "de": "de",
        "it": "it",
        "pt": "pt",
        "pt_br": "pt",
    }
    normalized = blender_language.replace("-", "_")
    for prefix, language_code in blender_map.items():
        if normalized.startswith(prefix):
            return language_code
    return "en"


def tr(key, default=None, language=None, **kwargs):
    lang = (language or get_effective_language()).lower()
    table = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    text = table.get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key, default if default is not None else key)
    try:
        return text.format(**kwargs)
    except Exception:
        return text


def yes_no(value, language=None):
    return tr("ui.yes" if value else "ui.no", language=language)
